// Generate and merge into locales
languages.forEach(lang => {
  const filePath = path.join(__dirname, 'src', 'locales', `${lang}.json`);
  let existing = {};
  if (fs.existsSync(filePath)) {
    try {
      existing = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    } catch (e) {
      console.warn(`Could not parse ${filePath}, starting fresh`);
    }
  }

  // Merge the new clean translations
  const merged = { ...existing };
  for (const [key, langMap] of Object.entries(translations)) {
    const val = langMap[lang] || langMap['en'];
    merged[key] = val;
    // Also provide dot notation alias for nested access
    merged[key.replace(/_/g, '.')] = val;
  }

  // Clean placeholder strings in en.json
  if (lang === 'en') {
    for (const [k, v] of Object.entries(merged)) {
      if (typeof v === 'string') {
        if (v.startsWith('Nav ') || v.startsWith('Auth ') || v.startsWith('Dash ') || v.startsWith('Header ') || v.startsWith('Irrig ') || v.startsWith('Weather ') || v.startsWith('Market ') || v.startsWith('Common ')) {
          // Replace with clean title case
          const clean = k.split('_').slice(1).map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
          merged[k] = clean;
        }
      }
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(merged, null, 2), 'utf8');
  console.log(`Updated ${lang}.json with ${Object.keys(merged).length} keys.`);
});
